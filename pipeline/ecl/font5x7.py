def text_width(s, z):
    """Advance is 6*z per glyph with the trailing inter-character gap removed."""
    return (6 * len(s) - 1) * z if len(s) else 0


def text_scale(s, width):
    """Largest scale at which the label still fits the panel it belongs to."""
    for z in range(5, 1, -1):
        if text_width(s, z) <= width:
            return z
    return 1


def glyph_mask(s, z):
    """Rasterise `s` at scale `z` into a boolean (7*z, width) mask.

    Unknown characters are skipped, leaving their advance blank — the same as the
    original's `if (!g) continue`.
    """
    s = str(s).upper()
    w = text_width(s, z)
    mask = np.zeros((7 * z, max(w, 1)), dtype=bool)
    for j, ch in enumerate(s):
        g = GLYPHS.get(ch)
        if g is None:
            continue
        gx = 6 * j * z
        for r in range(7):
            bits = g[r]
            for b in range(5):
                if not (bits & (1 << (4 - b))):
                    continue
                x0 = gx + b * z
                if x0 >= mask.shape[1]:
                    continue
                mask[r * z:(r + 1) * z, x0:min(x0 + z, mask.shape[1])] = True
    return mask
